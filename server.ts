// PAN + DOB IDENTITY VERIFICATION FOR DOCUMENT ACCESS (WITH RATE LIMITING)
app.post('/api/v1/filings/:id/verify-identity', (req: Request, res: Response) => {
  const { pan, dateOfBirth } = req.body;
  const filing = filings.find((f) => f.id === req.params.id);
  if (!filing) {
    return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Filing not found' } });
  }

  const client = clients.find((c) => c.id === filing.clientId);
  if (!client) {
    return res.status(404).json({ success: false, error: { code: 'CLIENT_NOT_FOUND', message: 'Client not found' } });
  }

  // Rate Limiting Check: Max 5 attempts per 15 minutes
  const now = Date.now();
  const attemptInfo = panVerificationAttemptsMap.get(client.id) || { attempts: 0 };

  if (attemptInfo.lockedUntil && now < attemptInfo.lockedUntil) {
    const remainingMins = Math.ceil((attemptInfo.lockedUntil - now) / 60000);
    recordAudit('user-client-1', client.firstName + ' ' + client.lastName, 'CLIENT', 'PAN_VERIFICATION_LOCKED', 'Client', client.id, { remainingMins }, req.ip);
    return res.status(429).json({
      success: false,
      error: { code: 'TOO_MANY_ATTEMPTS', message: `Too many failed identity attempts. Please wait ${remainingMins} minutes before trying again.` },
    });
  }

  const cleanPan = (pan || '').trim().toUpperCase();
  const cleanDob = (dateOfBirth || '').trim();

  const isPanMatch = cleanPan === client.pan;
  const isDobMatch = cleanDob === client.dateOfBirth;

  if (!isPanMatch || !isDobMatch) {
    attemptInfo.attempts += 1;
    if (attemptInfo.attempts >= 5) {
      attemptInfo.lockedUntil = now + 15 * 60 * 1000; // 15 mins lock
    }
    panVerificationAttemptsMap.set(client.id, attemptInfo);

    recordAudit('user-client-1', client.firstName + ' ' + client.lastName, 'CLIENT', 'PAN_VERIFICATION_FAILED', 'Client', client.id, { attemptCount: attemptInfo.attempts }, req.ip);

    return res.status(401).json({
      success: false,
      error: { code: 'VERIFICATION_FAILED', message: 'Invalid PAN or Date of Birth entered. Please verify credentials on file.' },
    });
  }

  // Success: Clear attempts & mark verified
  panVerificationAttemptsMap.delete(client.id);
  filing.panDobVerified = true;
  if (filing.paymentStatus === 'SUCCESS') {
    filing.status = 'DOWNLOAD_UNLOCKED';
    filing.progress = 100;
  }

  recordAudit('user-client-1', client.firstName + ' ' + client.lastName, 'CLIENT', 'PAN_VERIFICATION_SUCCESS', 'Client', client.id, {}, req.ip);

  res.json({
    success: true,
    message: 'Identity verified successfully!',
    filing,
  });
});

// SERVER-SIDE DOWNLOAD LOCK & SHORT-LIVED SIGNED DOWNLOAD URL
app.post('/api/v1/documents/:requirementId/download-url', (req: Request, res: Response) => {
  const reqItem = requirements.find((r) => r.id === req.params.requirementId);
  if (!reqItem || !reqItem.currentDocument) {
    return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Document requirement not found' } });
  }

  const filing = filings.find((f) => f.id === reqItem.filingId);
  if (!filing) {
    return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Filing not found' } });
  }

  // SERVER-SIDE LOCK CHECKS
  // Check 1: Payment Check
  if (filing.paymentStatus !== 'SUCCESS') {
    return res.status(403).json({
      success: false,
      error: {
        code: 'PAYMENT_REQUIRED',
        message: 'Payment is pending. Please complete fee payment to unlock document download.',
      },
    });
  }

  // Check 2: Identity Verification Check (PAN + DOB)
  if (!filing.panDobVerified) {
    return res.status(403).json({
      success: false,
      error: {
        code: 'IDENTITY_VERIFICATION_REQUIRED',
        message: 'PAN and Date of Birth verification required before downloading financial tax documents.',
      },
    });
  }

  // Generate 5-Minute Short-Lived Signed URL
  const version = reqItem.currentDocument.latestVersion;
  const expiresAt = new Date(Date.now() + 5 * 60 * 1000).toISOString(); // 5 minutes
  const signedToken = crypto.createHmac('sha256', 'taxvault-dl-secret').update(`${version.id}-${expiresAt}`).digest('hex');

  const downloadUrl = version.contentUrl || 'https://www.w3.org/WAI/ER/tests/xhtml/testfiles/resources/pdf/dummy.pdf';

  // Log Download Event
  const dlEvent: DownloadEvent = {
    id: `dl-${Date.now()}`,
    tenantId: tenant.id,
    clientId: filing.clientId,
    filingId: filing.id,
    documentId: reqItem.currentDocument.id,
    documentName: reqItem.name,
    userId: 'user-client-1',
    userName: filing.clientName,
    timestamp: new Date().toISOString(),
    ipAddress: req.ip || '127.0.0.1',
    userAgent: (req.headers['user-agent'] as string) || 'TaxVault Client Web',
    success: true,
  };
  downloadEvents.unshift(dlEvent);

  recordAudit('user-client-1', filing.clientName, 'CLIENT', 'DOCUMENT_DOWNLOADED', 'DocumentRequirement', reqItem.id, { documentName: reqItem.name, fileName: version.fileName }, req.ip);

  res.json({
    success: true,
    downloadUrl,
    signedToken,
    expiresAt,
    expiresInSeconds: 300,
    fileName: version.fileName,
  });
});

