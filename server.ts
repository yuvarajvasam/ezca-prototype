// CONFIRM UPLOAD (CREATES / UPDATES DOCUMENT VERSION & FILING STATUS)
app.post('/api/v1/documents/confirm-upload', (req: Request, res: Response) => {
  const { requirementId, fileName, fileType, fileSize, simulatedContentUrl } = req.body;
  const reqItem = requirements.find((r) => r.id === requirementId);
  if (!reqItem) {
    return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Requirement not found' } });
  }

  const filing = filings.find((f) => f.id === reqItem.filingId);
  if (!filing) {
    return res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Filing not found' } });
  }

  const newVersionNumber = reqItem.currentDocument ? reqItem.currentDocument.versions.length + 1 : 1;
  const newVersion: DocumentVersion = {
    id: `ver-${Date.now()}`,
    documentId: reqItem.currentDocument ? reqItem.currentDocument.id : `doc-${Date.now()}`,
    versionNumber: newVersionNumber,
    fileName: fileName || 'Uploaded_Document.pdf',
    fileType: fileType || 'application/pdf',
    fileSize: fileSize || 500000,
    contentUrl: simulatedContentUrl || 'https://www.w3.org/WAI/ER/tests/xhtml/testfiles/resources/pdf/dummy.pdf',
    uploadedAt: new Date().toISOString(),
    uploadedBy: filing.clientName,
  };

  if (!reqItem.currentDocument) {
    reqItem.currentDocument = {
      id: newVersion.documentId,
      status: 'UNDER_REVIEW',
      latestVersion: newVersion,
      versions: [newVersion],
    };
  } else {
    reqItem.currentDocument.versions.unshift(newVersion);
    reqItem.currentDocument.latestVersion = newVersion;
    reqItem.currentDocument.status = 'UNDER_REVIEW';
  }

  reqItem.status = 'UNDER_REVIEW';
  reqItem.rejectionReason = undefined;
  reqItem.updatedAt = new Date().toISOString();

  // Recalculate filing received documents & progress
  const filingReqs = requirements.filter((r) => r.filingId === filing.id);
  const received = filingReqs.filter((r) => r.status === 'APPROVED' || r.status === 'UNDER_REVIEW').length;
  filing.receivedDocuments = received;
  filing.progress = Math.round((received / Math.max(1, filing.totalDocuments)) * 80);

  if (filing.status === 'DOCUMENTS_REQUESTED' || filing.status === 'ADDITIONAL_DOCUMENTS_REQUIRED') {
    filing.status = 'DOCUMENTS_PARTIALLY_SUBMITTED';
  }
  if (received >= filing.totalDocuments) {
    filing.status = 'DOCUMENTS_SUBMITTED';
  }

  recordAudit('user-client-1', filing.clientName, 'CLIENT', 'DOCUMENT_UPLOADED', 'DocumentRequirement', reqItem.id, { requirementName: reqItem.name, versionNumber: newVersionNumber, fileName: newVersion.fileName }, req.ip);

  res.json({ success: true, requirement: reqItem, filing });
});

