app.post('/api/auth/login', (req: Request, res: Response) => {
  try {
    const { emailOrMobile, password, role } = req.body;
    const input = (emailOrMobile || '').trim().toLowerCase();
    const panInput = (emailOrMobile || '').trim().toUpperCase();

    if (!input) {
      return res.status(400).json({ success: false, error: 'Email, mobile number, or PAN is required.' });
    }

    // Look for user by email, mobile, or linked client PAN
    let matchedUser = users.find(
      (u) =>
        (u.email && u.email.toLowerCase() === input) ||
        (u.mobile && u.mobile.replace(/\D/g, '').endsWith(input.replace(/\D/g, ''))) ||
        (role === 'CLIENT' && clients.some((c) => c.pan === panInput && c.email.toLowerCase() === u.email.toLowerCase()))
    );

    // If searching by PAN for client
    if (!matchedUser && role === 'CLIENT') {
      const matchedClient = clients.find((c) => c.pan === panInput || c.mobile.includes(input) || c.email.toLowerCase() === input);
      if (matchedClient) {
        matchedUser = users.find((u) => u.email.toLowerCase() === matchedClient.email.toLowerCase() || u.mobile === matchedClient.mobile);
        if (!matchedUser) {
          matchedUser = {
            id: `user-${matchedClient.id}`,
            tenantId: tenant.id,
            mobile: matchedClient.mobile,
            email: matchedClient.email,
            name: `${matchedClient.firstName} ${matchedClient.lastName}`.trim(),
            role: 'CLIENT',
          };
          users.push(matchedUser);
        }
      }
    }

    // Fallback demo matching if specific role is requested
    if (!matchedUser) {
      if (role === 'CA_ADMIN' || role === 'ADMIN') {
        matchedUser = users.find((u) => u.role === 'CA_ADMIN') || users[0];
      } else if (role === 'CLIENT') {
        matchedUser = users.find((u) => u.role === 'CLIENT') || users[2];
      }
    }

    if (!matchedUser) {
      return res.status(401).json({ success: false, error: 'Account not found. Please check your credentials or create a new account.' });
    }

    // Validate role isolation
    if ((role === 'CA_ADMIN' || role === 'ADMIN') && matchedUser.role !== 'CA_ADMIN') {
      return res.status(403).json({ success: false, error: 'Access denied. This account does not have CA Admin privileges. Please use the Client Portal.' });
    }
    if (role === 'CLIENT' && matchedUser.role !== 'CLIENT') {
      return res.status(403).json({ success: false, error: 'This is a CA Admin account. Please sign in via the Admin Portal.' });
    }

    // Optional password check (allow demo passwords or registered passwords)
    const storedPassword = userPasswords.get(matchedUser.email.toLowerCase());
    if (storedPassword && password && password !== storedPassword && password !== 'admin123' && password !== 'client123' && password !== 'password123') {
      return res.status(401).json({ success: false, error: 'Incorrect password. Please try again.' });
    }

    // If client, resolve client object
    let clientObj = null;
    if (matchedUser.role === 'CLIENT') {
      clientObj = clients.find(
        (c) => c.email.toLowerCase() === matchedUser?.email.toLowerCase() || c.mobile === matchedUser?.mobile || c.id === matchedUser?.id.replace('user-', '')
      ) || clients[0];
    }

    recordAudit(matchedUser.id, matchedUser.name, matchedUser.role as any, 'USER_LOGIN', 'User', matchedUser.id, { email: matchedUser.email, role: matchedUser.role }, req.ip);

    return res.json({
      success: true,
      user: matchedUser,
      client: clientObj,
      tenant,
      token: `taxvault-token-${matchedUser.id}-${Date.now()}`,
      message: `Welcome back, ${matchedUser.name}!`,
    });
  } catch (err: any) {
    console.error('Login error:', err);
    return res.status(500).json({ success: false, error: err?.message || 'Server error during login' });
  }
});

